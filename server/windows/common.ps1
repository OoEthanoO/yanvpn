function Get-RealityUrl([object] $Config, [object] $Client) {
    $fragment = [Uri]::EscapeDataString("yanvpn-$($Client.Name)")
    if ($Config.Reality.Mode -eq 'CaddyWebSocket') {
        $path = [Uri]::EscapeDataString([string] $Config.Reality.Path)
        return "vless://$($Client.RealityUuid)@$($Config.Endpoint):$($Config.Reality.Port)?type=ws&security=tls&encryption=none&sni=$($Config.Endpoint)&host=$($Config.Endpoint)&path=$path#$fragment"
    }
    "vless://$($Client.RealityUuid)@$($Config.Endpoint):$($Config.Reality.Port)?type=tcp&security=reality&encryption=none&flow=xtls-rprx-vision&sni=$($Config.Reality.Sni)&fp=chrome&pbk=$($Config.Reality.PublicKey)&sid=$($Config.Reality.ShortId)#$fragment"
}

function Get-RealityClientConfig([object] $Config, [object] $Client) {
    if ($Config.Reality.Mode -eq 'CaddyWebSocket') {
        $proxyOutbound = [ordered]@{
            type = 'vless'; tag = 'proxy'; server = $Config.Endpoint
            server_port = [int] $Config.Reality.Port; uuid = $Client.RealityUuid; network = 'tcp'
            tls = [ordered]@{ enabled = $true; server_name = $Config.Endpoint }
            transport = [ordered]@{
                type = 'ws'; path = $Config.Reality.Path
                headers = [ordered]@{ Host = $Config.Endpoint }
            }
        }
    } else {
        $proxyOutbound = [ordered]@{
            type = 'vless'; tag = 'proxy'; server = $Config.Endpoint
            server_port = [int] $Config.Reality.Port; uuid = $Client.RealityUuid
            flow = 'xtls-rprx-vision'; network = 'tcp'
            tls = [ordered]@{
                enabled = $true; server_name = $Config.Reality.Sni
                utls = [ordered]@{ enabled = $true; fingerprint = 'chrome' }
                reality = [ordered]@{ enabled = $true; public_key = $Config.Reality.PublicKey; short_id = $Config.Reality.ShortId }
            }
        }
    }
    [ordered]@{
        log = [ordered]@{ level = 'warn'; timestamp = $true }
        dns = [ordered]@{
            servers = @(
                [ordered]@{ tag = 'remote'; type = 'tcp'; server = '1.1.1.1'; detour = 'proxy' },
                [ordered]@{ tag = 'local'; type = 'local' }
            )
            final = 'remote'; strategy = 'ipv4_only'
        }
        inbounds = @([ordered]@{
            type = 'tun'; tag = 'tun-in'; address = @('172.19.0.1/30')
            auto_route = $true; strict_route = $true; stack = 'system'
        })
        outbounds = @($proxyOutbound, [ordered]@{ type = 'direct'; tag = 'direct' })
        route = [ordered]@{
            rules = @(
                [ordered]@{ action = 'sniff' },
                [ordered]@{ protocol = 'dns'; action = 'hijack-dns' },
                [ordered]@{ network = 'udp'; port = 443; action = 'reject' },
                [ordered]@{ ip_is_private = $true; outbound = 'direct' }
            )
            final = 'proxy'; auto_detect_interface = $true; default_domain_resolver = 'local'
        }
    }
}

function Write-ClientFiles([object] $Config, [object] $Client) {
    $dir = Join-Path $script:YanVpnClientsPath $Client.Name
    New-Item -ItemType Directory -Force -Path $dir | Out-Null
    [IO.File]::WriteAllText((Join-Path $dir 'wg.conf'), (Get-WireGuardClientConfig $Config $Client).TrimStart(), [Text.Encoding]::ASCII)
    [IO.File]::WriteAllText((Join-Path $dir 'awg.conf'), (Get-AmneziaClientConfig $Config $Client).TrimStart(), [Text.Encoding]::ASCII)
    [IO.File]::WriteAllText((Join-Path $dir 'reality.url'), (Get-RealityUrl $Config $Client) + [Environment]::NewLine, [Text.Encoding]::ASCII)
    Write-YanVpnJson (Join-Path $dir 'reality.json') (Get-RealityClientConfig $Config $Client)
    Write-YanVpnJson (Join-Path $dir 'transports.json') ([ordered]@{
        WireGuard = Test-TransportEnabled $Config 'WireGuard'
        AmneziaWG = Test-TransportEnabled $Config 'AmneziaWG'
        Reality = $true
    })
    [IO.File]::WriteAllText((Join-Path $dir 'sing-box-version.txt'), [string] $Config.Reality.SingBoxVersion, [Text.Encoding]::ASCII)
}

function Install-TunnelService([string] $Program, [string] $TunnelName, [string] $ConfigPath, [string] $ServicePrefix) {
    $serviceName = "$ServicePrefix`$$TunnelName"
    if (Get-Service -Name $serviceName -ErrorAction SilentlyContinue) {
        & $Program /uninstalltunnelservice $TunnelName | Out-Null
        Start-Sleep -Milliseconds 500
    }
    Invoke-Checked $Program /installtunnelservice $ConfigPath
}

function Register-RealityTask([string] $ConfigPath) {
    if (Get-ScheduledTask -TaskName $script:RealityTask -ErrorAction SilentlyContinue) {
        Stop-ScheduledTask -TaskName $script:RealityTask -ErrorAction SilentlyContinue
        Unregister-ScheduledTask -TaskName $script:RealityTask -Confirm:$false
    }
    Get-CimInstance Win32_Process -Filter "Name='sing-box.exe'" -ErrorAction SilentlyContinue |
        Where-Object { $_.CommandLine -like "*$ConfigPath*" } |
        ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }
    $action = New-ScheduledTaskAction -Execute $script:SingBoxExe -Argument "run -c `"$ConfigPath`""
    $trigger = New-ScheduledTaskTrigger -AtStartup
    $settings = New-ScheduledTaskSettingsSet -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) -ExecutionTimeLimit ([TimeSpan]::Zero)
    Register-ScheduledTask -TaskName $script:RealityTask -Action $action -Trigger $trigger -Settings $settings -User 'SYSTEM' -RunLevel Highest -ErrorAction Stop | Out-Null
}

function Update-ServerRuntime {
    param([switch] $DoNotRestart)
    $config = Read-YanVpnConfig
    $wgConfig = Join-Path $script:YanVpnRoot "$($script:WireGuardTunnel).conf"
    $awgConfig = Join-Path $script:YanVpnRoot "$($script:AmneziaTunnel).conf"
    $realityConfig = Join-Path $script:YanVpnRoot 'reality-server.json'
    [IO.File]::WriteAllText($wgConfig, (Get-WireGuardServerConfig $config).TrimStart(), [Text.Encoding]::ASCII)
    [IO.File]::WriteAllText($awgConfig, (Get-AmneziaServerConfig $config).TrimStart(), [Text.Encoding]::ASCII)
    Write-YanVpnJson $realityConfig (Get-RealityServerConfig $config)
    Invoke-Checked $script:SingBoxExe check -c $realityConfig
    if (-not $DoNotRestart) {
        $routingScript = Join-Path $script:YanVpnRoot 'routing-ics.ps1'
        if ($config.PSObject.Properties.Name -contains 'Routing' -and $config.Routing.Mode -eq 'Ics' -and (Test-Path -LiteralPath $routingScript)) {
            & $routingScript -Disable
        }
        if (Test-TransportEnabled $config 'WireGuard') {
            Install-TunnelService $script:WireGuardExe $script:WireGuardTunnel $wgConfig 'WireGuardTunnel'
        } elseif (Get-Service -Name "WireGuardTunnel`$$($script:WireGuardTunnel)" -ErrorAction SilentlyContinue) {
            & $script:WireGuardExe /uninstalltunnelservice $script:WireGuardTunnel | Out-Null
        }
        if (Test-TransportEnabled $config 'AmneziaWG') {
            Install-TunnelService $script:AmneziaExe $script:AmneziaTunnel $awgConfig 'AmneziaWGTunnel'
        }
        Register-RealityTask $realityConfig
        Start-ScheduledTask -TaskName $script:RealityTask -ErrorAction Stop
        Start-Sleep -Seconds 1
        if ($config.PSObject.Properties.Name -contains 'Routing' -and $config.Routing.Mode -eq 'Ics') {
            if (Test-Path -LiteralPath $routingScript) { & $routingScript }
        }
    }
}



function Write-Step([string] $Message) { Write-Host "==> $Message" -ForegroundColor Cyan }
function Write-Ok([string] $Message) { Write-Host "  [ok] $Message" -ForegroundColor Green }
function Write-Warn([string] $Message) { Write-Host "  [!] $Message" -ForegroundColor Yellow }

function Assert-Administrator {
    $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = [Security.Principal.WindowsPrincipal]::new($identity)
    if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
        throw 'Run this command from PowerShell as Administrator.'
    }
}

function Initialize-StateDirectory {
    New-Item -ItemType Directory -Force -Path $script:YanVpnRoot, $script:YanVpnClientsPath, $script:YanVpnBinPath | Out-Null
    # State contains every private key. Keep access to SYSTEM and administrators.
    & icacls.exe $script:YanVpnRoot '/inheritance:r' '/grant:r' '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "Could not secure $script:YanVpnRoot" }
}

function Read-YanVpnConfig {
    if (-not (Test-Path -LiteralPath $script:YanVpnConfigPath)) {
        throw 'yanvpn is not installed on this server. Run server\windows\install.ps1 first.'
    }
    Get-Content -Raw -LiteralPath $script:YanVpnConfigPath | ConvertFrom-Json
}

function Write-YanVpnJson([string] $Path, [object] $Value) {
    $json = $Value | ConvertTo-Json -Depth 20
    [IO.File]::WriteAllText($Path, $json + [Environment]::NewLine, [Text.UTF8Encoding]::new($false))
}

function Invoke-Checked {
    param([Parameter(Mandatory)][string] $FilePath, [Parameter(ValueFromRemainingArguments)][string[]] $Arguments)
    & $FilePath @Arguments
    if ($LASTEXITCODE -ne 0) { throw "$FilePath failed with exit code $LASTEXITCODE" }
}

function Get-WgPublicKey([string] $PrivateKey) {
    $result = $PrivateKey | & $script:WgExe pubkey
    if ($LASTEXITCODE -ne 0) { throw 'wg pubkey failed.' }
    $result.Trim()
}

function New-WgPrivateKey {
    $result = & $script:WgExe genkey
    if ($LASTEXITCODE -ne 0) { throw 'wg genkey failed.' }
    $result.Trim()
}

function New-WgPresharedKey {
    $result = & $script:WgExe genpsk
    if ($LASTEXITCODE -ne 0) { throw 'wg genpsk failed.' }
    $result.Trim()
}

function Get-ClientRecords {
    if (-not (Test-Path -LiteralPath $script:YanVpnClientsPath)) { return @() }
    @(
        Get-ChildItem -LiteralPath $script:YanVpnClientsPath -Directory -ErrorAction SilentlyContinue |
            ForEach-Object {
                $meta = Join-Path $_.FullName 'meta.json'
                if (Test-Path -LiteralPath $meta) { Get-Content -Raw -LiteralPath $meta | ConvertFrom-Json }
            }
    )
}

function Get-NextClientHost {
    $used = @((Get-ClientRecords | ForEach-Object { [int] $_.Host }))
    foreach ($hostOctet in 2..254) {
        if ($used -notcontains $hostOctet) { return $hostOctet }
    }
    throw 'No free client addresses remain.'
}

function Get-WireGuardServerConfig([object] $Config) {
    $peers = foreach ($client in Get-ClientRecords) {
        @"

[Peer]
# yanvpn-client: $($client.Name)
PublicKey = $($client.WireGuard.PublicKey)
PresharedKey = $($client.WireGuard.PresharedKey)
AllowedIPs = $($Config.WireGuard.Subnet).$($client.Host)/32
"@
    }
    @"
# Generated by yanvpn. Do not edit; use vpnctl.ps1.
[Interface]
PrivateKey = $($Config.WireGuard.PrivateKey)
Address = $($Config.WireGuard.Subnet).1/24
ListenPort = $($Config.WireGuard.Port)
$($peers -join '')
"@
}

function Test-TransportEnabled([object] $Config, [string] $Name) {
    $transport = $Config.$Name
    if ($null -eq $transport) { return $false }
    if ($transport.PSObject.Properties.Name -notcontains 'Enabled') { return $true }
    return [bool] $transport.Enabled
}


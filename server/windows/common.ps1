function Get-RealityServerConfig([object] $Config) {
    $baseUsers = @(
        Get-ClientRecords | ForEach-Object {
            [ordered]@{ uuid = $_.RealityUuid; name = $_.Name }
        }
    )
    $inbounds = @()
    if ($Config.Reality.Mode -in @('CaddyWebSocket','Dual')) {
        $inbounds += [ordered]@{
            type = 'vless'; tag = 'vless-ws'; listen = '127.0.0.1'; listen_port = [int] $Config.Reality.InternalPort
            users = $baseUsers
            transport = [ordered]@{ type = 'ws'; path = $Config.Reality.Path }
        }
    }
    if ($Config.Reality.Mode -in @('Reality','Dual')) {
        $realityUsers = @($baseUsers | ForEach-Object {
            [ordered]@{ uuid = $_.uuid; flow = 'xtls-rprx-vision'; name = $_.name }
        })
        $inbounds += [ordered]@{
            type = 'vless'; tag = 'vless-reality'; listen = '::'; listen_port = [int] $Config.Reality.Port
            users = $realityUsers
            tls = [ordered]@{
                enabled = $true; server_name = $Config.Reality.Sni
                reality = [ordered]@{
                    enabled = $true
                    handshake = [ordered]@{ server = $Config.Reality.Sni; server_port = 443 }
                    private_key = $Config.Reality.PrivateKey
                    short_id = @($Config.Reality.ShortId)
                }
            }
        }
    }
    [ordered]@{
        log = [ordered]@{ level = 'warn'; timestamp = $true }
        inbounds = @($inbounds)
        outbounds = @([ordered]@{ type = 'direct'; tag = 'direct' })
    }
}

